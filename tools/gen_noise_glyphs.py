"""TRAUMA's screen (0.14.8): Audiotrauma's slogan, VOUS ETES LE over BRUIT, and the same in six more languages, its
letters thrown at random as fast as the screen goes. Two sets of glyphs, one a line: Anton (an open Impact,
firmware/fonts/Anton-Regular.ttf, SIL OFL 1.1) at 49 px for the first line and at 115 px for the second, as wide; the
kana in Dela Gothic One (firmware/fonts/DelaGothicOne-kana.ttf: its kana alone, Fontsource's @fontsource/dela-gothic-one
5.3.0, SIL OFL 1.1), each in a box of the line's cap height. Only the letters the phrases use (the random ones drawn
from them too), each glyph's rows in runs (a byte: its 4-bit coverage and a length of 1 to 16): Anton's letters are
mostly solid, a run a stroke, 4 times less room than fm1-base's fonts (the flash is nearly full).

    tools/gen_noise_glyphs.py         -> firmware/noise_glyphs.h"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "firmware" / "fonts"
OUT = ROOT / "firmware" / "noise_glyphs.h"

# (language, first line, second line): each line no wider than VOUS ETES LE and BRUIT (12 and 5 letters), its words
# as a speaker would write the slogan (BRUSET and RUMORE, six letters, too wide at 115 px: rent oljud, pure noise;
# rumor, Italian's poetic form)
PHRASES = [
    ("fr", "VOUS ÊTES LE", "BRUIT"),
    ("en", "YOU ARE THE", "NOISE"),
    ("ja", "あなたたちは", "ノイズだ"),
    ("cs", "VY JSTE TEN", "HLUK"),
    ("de", "IHR SEID DER", "KRACH"),
    ("it", "VOI SIETE IL", "RUMOR"),
    ("sv", "NI ÄR RENT", "OLJUD"),
]
# the two lines: Anton's size, its letters' tracking, a space's advance, the kana's box (width, its advance)
LINES = [dict(px=49, track=-1, space=10, kana_w=36), dict(px=115, track=-3, space=24, kana_w=54)]


def is_kana(c):
    return 0x3000 <= ord(c) <= 0x30FF


def runs(img):
    """the glyph's rows in runs: (coverage >> 4) << 4 | (length - 1), lengths 1..16, never across a row"""
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        x = 0
        while x < w:
            v = px[x, y] >> 4
            n = 1
            while x + n < w and n < 16 and px[x + n, y] >> 4 == v:
                n += 1
            out.append(v << 4 | (n - 1))
            x += n
    return out


def glyph_latin(font, c, cap_top):
    """a letter: its ink's box, where it sits against the pen (x) and the cap top (y), its advance"""
    l, t, r, b = font.getbbox(c)
    img = Image.new("L", (r - l + 2, b - t + 2), 0)
    ImageDraw.Draw(img).text((1 - l, 1 - t), c, font=font, fill=255)
    return img, l - 1, t - 1 - cap_top, int(round(font.getlength(c)))


def glyph_kana(c, box_w, box_h):
    """a kana drawn large, its ink stretched into box_w x box_h (Anton's cap height: the line's), then its advance"""
    f = ImageFont.truetype(str(FONTS / "DelaGothicOne-kana.ttf"), 400)
    l, t, r, b = f.getbbox(c)
    big = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(big).text((-l, -t), c, font=f, fill=255)
    small = big.resize((box_w - 2, box_h), Image.LANCZOS)
    img = Image.new("L", (box_w, box_h + 2), 0)
    img.paste(small, (1, 1))
    return img, 0, -1, box_w + 2


def main():
    out = ["/* generated by tools/gen_noise_glyphs.py: TRAUMA's screen, the slogan in seven languages. Anton (SIL OFL 1.1:",
           " * fonts/Anton-OFL.txt), the kana in Dela Gothic One (SIL OFL 1.1: fonts/DelaGothicOne-OFL.txt). A glyph: its",
           " * box (w x h), where it sits against the pen and the line's cap top, its advance, its rows in runs (a byte:",
           " * 4-bit coverage << 4 | length - 1) */", "#pragma once",
           "typedef struct { uint8_t w, h, adv, latin; int8_t x0, y0; uint16_t off; } noise_glyph_t;"]
    total = 0
    for li, line in enumerate(LINES):
        font = ImageFont.truetype(str(FONTS / "Anton-Regular.ttf"), line["px"])
        cap_top, base = font.getbbox("E")[1], font.getbbox("E")[3]
        chars = []
        for _, *ls in PHRASES:
            for c in ls[li]:
                if c != " " and c not in chars:
                    chars.append(c)
        chars.sort(key=lambda c: (is_kana(c), c))
        data, rows = [], []
        for c in chars:
            if is_kana(c):
                img, x0, y0, adv = glyph_kana(c, line["kana_w"], base - cap_top)
            else:
                img, x0, y0, adv = glyph_latin(font, c, cap_top)
            rows.append(f"    {{{img.size[0]}, {img.size[1]}, {adv}, {0 if is_kana(c) else 1}, {x0}, {y0}, {len(data)}}},"
                        f"   /* {c} */")
            data += runs(img)
        n_latin = sum(1 for c in chars if not is_kana(c))
        out.append(f"/* line {li + 1}: Anton {line['px']} px, its cap height {base - cap_top} px, {len(chars)} glyphs "
                   f"({n_latin} letters, then the kana), {len(data)} B */")
        out.append(f"static const noise_glyph_t NOISE{li + 1}_G[{len(chars)}] = {{")
        out += rows
        out.append("};")
        out.append(f"static const uint8_t NOISE{li + 1}_RUNS[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"#define NOISE{li + 1}_N {len(chars)}")
        out.append(f"#define NOISE{li + 1}_LATIN {n_latin}")
        out.append(f"#define NOISE{li + 1}_TRACK ({line['track']})")
        out.append(f"#define NOISE{li + 1}_SPACE {line['space']}")
        out.append(f"#define NOISE{li + 1}_CAP {base - cap_top}")
        line["chars"] = chars
        total += len(data) + 8 * len(chars)
    # the phrases: each line its glyphs (0xFF a space, 0xFE the end)
    out.append(f"#define NOISE_LANGS {len(PHRASES)}")
    out.append("static const char *const NOISE_LANG_NAME[NOISE_LANGS] = {" +
               ", ".join(f'"{p[0]}"' for p in PHRASES) + "};")
    for li, line in enumerate(LINES):
        width = 13 if li == 0 else 6
        out.append(f"static const uint8_t NOISE{li + 1}_PHRASE[NOISE_LANGS][{width}] = {{")
        for p in PHRASES:
            s = p[1 + li]
            assert len(s) < width, s
            ids = [255 if c == " " else line["chars"].index(c) for c in s] + [254]
            out.append("    {" + ", ".join(str(v) for v in ids) + f"}},   /* {p[0]}: {s} */")
        out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.name}: {total} B ({', '.join(str(len(l['chars'])) for l in LINES)} glyphs)")


main()
