"""MIFM1's name at power-on and the random dose's screen, in Syne ExtraBold (firmware/fonts: Syne[wght].ttf from
google/fonts' ofl/syne, SIL OFL 1.1, Syne-OFL.txt): firmware/logo_font.h (FONT_LOGO, 31 px) and firmware/rand_font.h
(FONT_RAND, 48 px: RAN over DOM), felucca fonts (fm1-base tools/gen_font.py's format and rendering: 4-bit
anti-aliasing) with only the signs written, the words' and those their letters pass through on their way (the others
are empty: nothing drawn, no room taken).

    tools/gen_logo_font.py"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "firmware" / "fonts" / "Syne[wght].ttf"
WGHT = 800
FONTS = [  # (name, px, signs, file, what)
    ("FONT_LOGO", 31, "MIFM1" + "#%+0268",   # (app.c LOGO_SIGNS: the ones after the name; Syne's other figures go
     "logo_font.h", "MIFM1's name at power-on"),   # under the line)
    ("FONT_RAND", 48, "RANDOM" + "#%+&?KXZ",   # (app.c RAND_SIGNS; '*' over and '@' under the others' rows)
     "rand_font.h", "the random dose's screen"),
]
PAD = 2                                        # (gen_font.py's)


def make(name, PX, SIGNS, file, what):
    OUT = ROOT / "firmware" / file
    font = ImageFont.truetype(str(TTF), PX)
    font.set_variation_by_axes([WGHT])
    asc, desc = font.getmetrics()
    used = sorted(set(SIGNS))
    ink = [font.getbbox(ch) for ch in used]          # the rows the signs use, and a row over and under them
    top = max(0, min(b[1] for b in ink) - 1)
    h = min(asc + desc, max(b[3] for b in ink) + 1) - top
    first, last = ord(used[0]), ord(used[-1])
    data, offs, advs, bws = [], [], [], []
    for c in range(first, last + 1):
        ch = chr(c)
        offs.append(len(data))
        if ch not in used:
            advs.append(0)
            bws.append(0)
            continue
        adv = int(round(font.getlength(ch)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255)
        img = img.crop((0, top, bw, top + h))
        px_ = [min(15, (v + 8) // 17) for v in img.tobytes()]
        for y in range(h):
            row = px_[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
        advs.append(adv)
        bws.append(bw)
    lines = [f"/* generated by tools/gen_logo_font.py: {what}, Syne ExtraBold "
             f"{PX} px (SIL OFL 1.1: fonts/Syne-OFL.txt), the signs {''.join(used)!r} alone */",
             "#pragma once",
             f"static const uint8_t {name}_DATA[{max(1, len(data))}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};",
              f"static const uint16_t {name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
              f"static const uint8_t {name}_ADV[{len(advs)}] = {{" + ", ".join(map(str, advs)) + "};",
              f"static const uint8_t {name}_BW[{len(bws)}] = {{" + ", ".join(map(str, bws)) + "};",
              f"static const felucca_font_t {name} = {{ {h}, {PAD}, {first}, {last}, {name}_ADV, {name}_BW, "
              f"{name}_OFF, {name}_DATA }};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: Syne {WGHT} {PX} px, h {h}, {len(used)} signs, {len(data)} B")


def main():
    for f in FONTS:
        make(*f)


if __name__ == "__main__":
    main()
