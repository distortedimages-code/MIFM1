"""MIFM1's name at power-on and the random dose's screen, in Syne ExtraBold (firmware/fonts: Syne[wght].ttf from
google/fonts' ofl/syne, SIL OFL 1.1, Syne-OFL.txt): firmware/logo_font.h (FONT_LOGO, 31 px) and firmware/rand_font.h
(FONT_RAND, 48 px: RAN over DOM). Felucca fonts (fm1-base tools/gen_font.py's format and rendering: 4-bit
anti-aliasing) with only the signs written, the words' and those their letters pass through on their way (the others
are empty: nothing drawn, no room taken). TRAUMA's screen: tools/gen_noise_glyphs.py.

    tools/gen_logo_font.py"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SYNE = ("Syne ExtraBold", "Syne[wght].ttf", 800, "Syne-OFL.txt")
MAP = {}                                       # (a sign beyond ASCII written at a free code: none now)
FONTS = [  # (name, face, px, signs, file, what)
    ("FONT_LOGO", SYNE, 31, "MIFM1" + "#%+0268",   # (app.c LOGO_SIGNS: the ones after the name; Syne's other figures
     "logo_font.h", "MIFM1's name at power-on"),   # go under the line)
    ("FONT_RAND", SYNE, 48, "RANDOM" + "#%+&?KXZ",   # (app.c RAND_SIGNS; '*' over and '@' under the others' rows)
     "rand_font.h", "the random dose's screen"),
]
PAD = 2                                        # (gen_font.py's)
written = {}                                   # (the files written this run: a second font appended)


def make(name, face, PX, SIGNS, file, what):
    OUT = ROOT / "firmware" / file
    label, ttf, wght, lic = face
    font = ImageFont.truetype(str(ROOT / "firmware" / "fonts" / ttf), PX)
    if wght:
        font.set_variation_by_axes([wght])
    asc, desc = font.getmetrics()
    used = sorted(set(SIGNS))
    ink = [font.getbbox(MAP.get(ch, ch)) for ch in used]   # the rows the signs use, and a row over and under them
    top = max(0, min(b[1] for b in ink) - 1)
    h = min(asc + desc, max(b[3] for b in ink) + 1) - top
    first, last = ord(used[0]), ord(used[-1])
    data, offs, advs, bws = [], [], [], []
    for c in range(first, last + 1):
        ch = chr(c)
        offs.append(len(data))
        if ch not in used:
            advs.append(0)
            bws.append(0)
            continue
        adv = int(round(font.getlength(MAP.get(ch, ch))))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), MAP.get(ch, ch), font=font, fill=255)
        img = img.crop((0, top, bw, top + h))
        px_ = [min(15, (v + 8) // 17) for v in img.tobytes()]
        for y in range(h):
            row = px_[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
        advs.append(adv)
        bws.append(bw)
    shown = "".join(MAP.get(ch, ch) + (f" (at {ch})" if ch in MAP else "") for ch in used)
    lines = [f"/* generated by tools/gen_logo_font.py: {what}, {label} "
             f"{PX} px (SIL OFL 1.1: fonts/{lic}), the signs {shown!r} alone */"]
    if OUT not in written:
        lines.append("#pragma once")
    lines.append(f"static const uint8_t {name}_DATA[{max(1, len(data))}] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};",
              f"static const uint16_t {name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
              f"static const uint8_t {name}_ADV[{len(advs)}] = {{" + ", ".join(map(str, advs)) + "};",
              f"static const uint8_t {name}_BW[{len(bws)}] = {{" + ", ".join(map(str, bws)) + "};",
              f"static const felucca_font_t {name} = {{ {h}, {PAD}, {first}, {last}, {name}_ADV, {name}_BW, "
              f"{name}_OFF, {name}_DATA }};", ""]
    OUT.write_text(written.get(OUT, "") + "\n".join(lines))
    written[OUT] = written.get(OUT, "") + "\n".join(lines)
    print(f"{OUT.name}: {label} {PX} px, h {h}, {len(used)} signs, {len(data)} B")


def main():
    for f in FONTS:
        make(*f)


if __name__ == "__main__":
    main()
