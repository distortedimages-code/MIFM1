"""MIFM1's name at power-on, in Syne ExtraBold (firmware/fonts: Syne[wght].ttf from google/fonts' ofl/syne, SIL OFL
1.1, Syne-OFL.txt): firmware/logo_font.h, a felucca font (fm1-base tools/gen_font.py's format and rendering: 4-bit
anti-aliasing) with only the signs the intro writes, the name's and those its letters pass through on their way
(the others are empty: nothing drawn, no room taken).

    tools/gen_logo_font.py"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "firmware" / "fonts" / "Syne[wght].ttf"
OUT = ROOT / "firmware" / "logo_font.h"
PX, WGHT = 31, 800
SIGNS = "MIFM1" + "#%+0268"   # (app.c LOGO_SIGNS: the ones after the name; Syne's other figures go under the line)
PAD = 2                                        # (gen_font.py's)


def main():
    font = ImageFont.truetype(str(TTF), PX)
    font.set_variation_by_axes([WGHT])
    asc, desc = font.getmetrics()
    used = sorted(set(SIGNS))
    ink = [font.getbbox(ch) for ch in used]          # the rows the signs use, and a row over and under them
    top = max(0, min(b[1] for b in ink) - 1)
    h = min(asc + desc, max(b[3] for b in ink) + 1) - top
    first, last = ord(used[0]), ord(used[-1])
    data, offs, advs, bws = [], [], [], []
    for c in range(first, last + 1):
        ch = chr(c)
        offs.append(len(data))
        if ch not in used:
            advs.append(0)
            bws.append(0)
            continue
        adv = int(round(font.getlength(ch)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255)
        img = img.crop((0, top, bw, top + h))
        px_ = [min(15, (v + 8) // 17) for v in img.tobytes()]
        for y in range(h):
            row = px_[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
        advs.append(adv)
        bws.append(bw)
    lines = ["/* generated by tools/gen_logo_font.py: MIFM1's name at power-on, Syne ExtraBold "
             f"{PX} px (SIL OFL 1.1: fonts/Syne-OFL.txt), the signs {''.join(used)!r} alone */",
             "#pragma once",
             f"static const uint8_t FONT_LOGO_DATA[{max(1, len(data))}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};",
              f"static const uint16_t FONT_LOGO_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
              f"static const uint8_t FONT_LOGO_ADV[{len(advs)}] = {{" + ", ".join(map(str, advs)) + "};",
              f"static const uint8_t FONT_LOGO_BW[{len(bws)}] = {{" + ", ".join(map(str, bws)) + "};",
              f"static const felucca_font_t FONT_LOGO = {{ {h}, {PAD}, {first}, {last}, FONT_LOGO_ADV, FONT_LOGO_BW, "
              "FONT_LOGO_OFF, FONT_LOGO_DATA };", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: Syne {WGHT} {PX} px, h {h}, {len(used)} signs, {len(data)} B")


if __name__ == "__main__":
    main()
